"""파일 올리기 안내문 (변환기·요약본 공용).

계약서 도구의 같은 안내문과 짝을 맞춘 것입니다. 문구를 고칠 일이 있으면
이 파일 한 곳만 고치면 두 화면에 같이 반영됩니다.

IM 은 계약서와 달리 **읽을 수 없는 PDF 가 두 종류**입니다.
  · 스캔본(사진으로 된 것)
  · 글자를 도형으로 바꿔 저장한 것 — 눈에는 글자가 또렷한데 컴퓨터는 못 읽습니다
    (실제로 22쪽짜리 IM 에서 뽑히는 글자가 648자뿐인 경우가 있었습니다)
다행히 둘 다 **같은 방법으로 1초에 확인**됩니다 — 글자를 드래그해 보면 됩니다.
"""

import streamlit as st

GUIDE_TITLE = "📎 파일 올리기 전에 꼭 읽어보세요 — 읽을 수 없는 PDF 확인법 · 워드를 PDF로 저장하는 법"

SCAN_WARNING = (
    "🚫 **글자를 읽을 수 없는 PDF 가 있습니다.**\n\n"
    "두 가지 경우입니다.\n\n"
    "1. **스캔본** — 복사기로 스캔하거나 사진을 찍어 만든 PDF. 겉보기엔 글자 같아도 "
    "컴퓨터에는 **그림 한 장**일 뿐입니다.\n"
    "2. **글자를 그림으로 바꿔 저장한 PDF** — 화면에는 글자가 또렷하게 보이는데도 "
    "컴퓨터는 못 읽습니다. 겉보기로는 멀쩡해 보여서 더 헷갈립니다.\n\n"
    "둘 다 표와 글을 가져올 수 없어 결과물이 거의 비어서 나옵니다.\n\n"
    "**내 PDF 가 어느 쪽인지 1초에 확인하는 법** — PDF 를 열어 본문 글자를 마우스로 **드래그**해 보세요. "
    "글자가 파랗게 선택되면 ✅ 그대로 올리면 됩니다. "
    "아무것도 안 잡히고 사진처럼 통째로 끌리면 ❌ 위 둘 중 하나입니다.\n\n"
    "❌ 인 경우에는 **글자가 살아 있는 원본**(보내준 쪽에 다시 요청하거나, 워드 원본에서 저장한 PDF)이 필요합니다."
)

WORD_TO_PDF = (
    "📄 **워드 파일밖에 없다면 — 워드에서 PDF 로 저장한 뒤 그 PDF 를 올려주세요.** "
    "이게 가장 정확하고 깨끗합니다.\n\n"
    "**PDF 로 저장하는 법 (30초)**\n"
    "1. 그 워드 파일을 **워드로 열기**\n"
    "2. 키보드 **`F12`** 누르기 → 옛날식 저장 창이 뜹니다\n"
    "   (`파일 → 다른 이름으로 저장` 을 누르면 형식 칸이 안 보이는 화면이 먼저 떠서, **F12 가 빠릅니다**)\n"
    "3. 아래 **파일 형식** 칸을 눌러 **`PDF (*.pdf)`** 선택\n"
    "4. **저장** → 같은 폴더에 이름이 같고 확장자만 `.pdf` 인 파일이 생깁니다\n"
    "5. 그 **PDF** 를 올리면 끝\n\n"
    "*(F12 가 안 되면 `파일 → 내보내기 → PDF/XPS 문서 만들기 → 게시` 도 같은 결과입니다)*\n\n"
    "**⚠️ 참고 — 알PDF 같은 무료 변환 프로그램은 권하지 않습니다.** "
    "글자가 깨지거나 통째로 그림으로 저장돼서, 앱이 표와 글을 못 읽는 경우가 있습니다. "
    "**워드에서 직접 저장(F12)** 한 PDF 가 가장 정확합니다."
)

TIP_BEST = (
    "💡 **가장 잘 나오는 원본** — 표에 테두리 선이 그어져 있고, 글자를 드래그하면 선택되는 PDF 입니다. "
    "이런 원본이면 표를 원본 모양 그대로(병합된 칸까지) 가져옵니다."
)


def render_upload_guide(expanded: bool = False):
    """접었다 폈다 하는 안내문. 파일 올리는 칸 **바로 위**에 한 번만 부릅니다."""
    with st.expander(GUIDE_TITLE, expanded=expanded):
        st.markdown(SCAN_WARNING)
        st.divider()
        st.markdown(WORD_TO_PDF)
        st.divider()
        st.markdown(TIP_BEST)


def render_upload_guide_boxes():
    """색깔 박스 모양(접지 않고 바로 보여주고 싶을 때)."""
    st.error(SCAN_WARNING)
    st.info(WORD_TO_PDF)
